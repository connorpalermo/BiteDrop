/**
 * Fixed reference point every firstSeenAt literal below is authored against.
 * Using a frozen constant (rather than the real wall clock) is what keeps the
 * dataset — and the tests that assert its coverage — reproducible forever.
 * Known limitation: since the web app renders relative time against the ACTUAL
 * current time, the "minutes ago" / "hours ago" variety here is calibrated to
 * 2026-09-11 and will visually compress toward absolute dates as real time
 * moves past it. Phase 2 replaces this dataset with live discovery timestamps.
 */
export const MOCK_NOW = '2026-09-11T12:00:00.000Z';

