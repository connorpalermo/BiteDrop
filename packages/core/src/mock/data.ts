/**
 * Composes the per-drop sources array from the fixed publication list above.
 * This is deliberately NOT "generating drops procedurally" (S13 rule 4) — every
 * drop's own identity (name, brand, description, dates) is hand-authored below;
 * this only fills in the repetitive nested source metadata so the file stays a
 * manageable size. Each source's discoveredAt trails firstSeenAt by a growing
 * offset, reflecting that corroborating coverage arrives after the first report.
 */
function makeSources(slug: string, name: string, count: number, firstSeenAt: string): SourceRef[] {
  const base = new Date(firstSeenAt).getTime();
  return Array.from({ length: count }, (_, i) => {
    const outlet = PUBLICATIONS[i % PUBLICATIONS.length]!;
    const discoveredAt = new Date(base + i * 3 * 60 * 60 * 1000).toISOString();
    return {
      id: `${slug}-src-${i + 1}`,
      sourceName: outlet.name,
      title: i === 0 ? `${name}: what we know` : `${name} spotted by ${outlet.name}`,
      url: outlet.baseUrl,
      publishedAt: discoveredAt,
      discoveredAt,
      isPrimary: i === 0,
    };
  });
}

